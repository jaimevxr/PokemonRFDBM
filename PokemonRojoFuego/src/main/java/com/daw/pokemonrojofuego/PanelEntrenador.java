    private void jButtonActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonActualizarActionPerformed
        // TODO add your handling code here:

        // Comprobamos que la caja del ID no esté vacía
        String idTexto = txtId.getText().trim();
        if (idTexto.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Primero debes buscar un entrenador para poder modificarlo.");
            return;
        }

        try {
            int id = Integer.parseInt(idTexto);
            EntrenadorDAO dao = new EntrenadorDAO();

            // Recuperamos al entrenador de la base de datos para asegurarnos de que sigue ahí
            Entrenador entrenadorAActualizar = dao.buscarPorId(id);

            if (entrenadorAActualizar != null) {
                // asignamos los nuevos valores
                entrenadorAActualizar.setNombreEntrenador(txtNombre.getText().trim());
                entrenadorAActualizar.setClase(txtClase.getText().trim());

                int nuevoDinero = Integer.parseInt(txtDinero.getText().trim());
                entrenadorAActualizar.setDinero(nuevoDinero);

                // Llamamos método DAO que usa em.merge()
                dao.actualizar(entrenadorAActualizar);

                javax.swing.JOptionPane.showMessageDialog(this, "¡Entrenador actualizado con éxito!");

                // volver a ejecutar la búsqueda del buscador para refrescar la pantalla
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "El entrenador ya no existe en la base de datos.");
            }

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: El dinero debe ser un número entero válido.");
        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al actualizar: " + ex.getMessage());
        }
    }//GEN-LAST:event_jButtonActualizarActionPerformed

    private void jButtonBorrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonBorrarActionPerformed
        // TODO add your handling code here:
        String idTexto = txtId.getText().trim();

        if (idTexto.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Busca primero al entrenador que deseas eliminar.");
            return;
        }

        int confirmacion = javax.swing.JOptionPane.showConfirmDialog(this, "¿Seguro que quieres borrar a este entrenador?", "Confirmar", javax.swing.JOptionPane.YES_NO_OPTION);

        if (confirmacion == javax.swing.JOptionPane.YES_OPTION) {
            try {
                int id = Integer.parseInt(idTexto);

                EntrenadorDAO dao = new EntrenadorDAO();
                dao.borrar(id);

                javax.swing.JOptionPane.showMessageDialog(this, "Entrenador eliminado con éxito.");

                // Limpiamos la pantalla
                txtId.setText("");
                txtNombre.setText("");
                txtClase.setText("");
                txtDinero.setText("");

                javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tablaPokemon.getModel();
                modelo.setRowCount(0);

            } catch (Exception ex) {
                javax.swing.JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
            }
        }


    }//GEN-LAST:event_jButtonBorrarActionPerformed

    private void jButtonBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonBuscarActionPerformed
        // Recogemos el texto del buscador
        String textoBuscador = txtBuscador.getText().trim();
        if (textoBuscador.isEmpty() || textoBuscador.equals("Buscar ID o Nombre")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, escribe un ID o un Nombre para buscar.");
            return;
        }

        EntrenadorDAO dao = new EntrenadorDAO();
        Entrenador entrenadorEncontrado = null;

        // Limpiamos la tabla 
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tablaPokemon.getModel();
        modelo.setRowCount(0);

        try {
            // Intentamos buscar por ID (si es número)
            int idBuscado = Integer.parseInt(textoBuscador);
            entrenadorEncontrado = dao.buscarPorId(idBuscado);
        } catch (NumberFormatException ex) {
            // Si no es número, buscamos por Nombre
            entrenadorEncontrado = dao.buscarPorNombre(textoBuscador);
        }

        // Si encontramos al entrenador, rellenamos todo
        if (entrenadorEncontrado != null) {
            txtId.setText(String.valueOf(entrenadorEncontrado.getIdEntrenador()));
            txtNombre.setText(entrenadorEncontrado.getNombreEntrenador());
            txtClase.setText(entrenadorEncontrado.getClase());
            txtDinero.setText(String.valueOf(entrenadorEncontrado.getDinero()));

            // Cargamos su equipo Pokémon en la tabla
            java.util.List<Pokemon> equipo = entrenadorEncontrado.getPokemon();

            if (equipo != null) {
                for (Pokemon p : equipo) {
                    Object[] fila = new Object[4];
                    fila[0] = p.getApodo();
                    fila[1] = p.getIdPokemon();
                    fila[2] = p.getNivel();

                    // tratar el sprite como BLOB
                    byte[] spriteBytes = p.getSprite();

                    if (spriteBytes != null && spriteBytes.length > 0) {
                        try {
                            // Convertimos los bytes directamente en una imagen gráfica
                            javax.swing.ImageIcon icono = new javax.swing.ImageIcon(spriteBytes);
                            // La redimensionamos para que quede bonita en la tabla
                            java.awt.Image img = icono.getImage().getScaledInstance(60, 60, java.awt.Image.SCALE_SMOOTH);
                            fila[3] = new javax.swing.ImageIcon(img);
                        } catch (Exception e) {
                            fila[3] = "Error imagen";
                        }
                    } else {
                        fila[3] = "Sin imagen";
                    }
                    modelo.addRow(fila);
                }
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Entrenador no encontrado.");
            // Vaciamos campos
            txtId.setText("");
            txtNombre.setText("");
            txtClase.setText("");
            txtDinero.setText("");
        }
    }//GEN-LAST:event_jButtonBuscarActionPerformed

