    private void jButtonGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonGuardarActionPerformed
        // TODO add your handling code here:
        // Recogemos los textos
        String nombre = txtNombre.getText().trim();
        String clase = txtClase.getText().trim();
        String dineroTexto = txtDinero.getText().trim();

        // Validamos que no deje campos vacíos
        if (nombre.isEmpty() || clase.isEmpty() || dineroTexto.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, rellena el Nombre, la Clase y el Dinero para crear un entrenador.");
            return;
        }

        try {
            // Convertimos el dinero a número
            int dinero = Integer.parseInt(dineroTexto);

            // Creamos el objeto Entrenador NUEVO
            Entrenador nuevoEntrenador = new Entrenador();
            nuevoEntrenador.setNombreEntrenador(nombre);
            nuevoEntrenador.setClase(clase);
            nuevoEntrenador.setDinero(dinero);

            // Lo guardamos en la base de datos
            EntrenadorDAO dao = new EntrenadorDAO();
            dao.guardar(nuevoEntrenador);

            // Le decimos al usuario qué ID exacto le ha asignado al entrenador
            javax.swing.JOptionPane.showMessageDialog(this,
                    "¡Nuevo entrenador creado con éxito!\nEl sistema le ha asignado el ID: " + nuevoEntrenador.getIdEntrenador());

            // Vaciamos las cajas
            txtId.setText("");
            txtNombre.setText("");
            txtClase.setText("");
            txtDinero.setText("");

            // Vaciamos también la tabla por si había datos de otro entrenador
            javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tablaPokemon.getModel();
            modelo.setRowCount(0);

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: El dinero debe ser un número entero.");
        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al guardar en la base de datos: " + ex.getMessage());
        }
    }//GEN-LAST:event_jButtonGuardarActionPerformed

